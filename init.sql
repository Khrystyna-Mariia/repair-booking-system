CREATE TABLE IF NOT EXISTS Users (
    id INT AUTO_INCREMENT PRIMARY KEY, fullName VARCHAR(255), email VARCHAR(255), password VARCHAR(255),
    role ENUM('client','master','admin'), phone VARCHAR(255), address VARCHAR(255), isBanned TINYINT(1) DEFAULT 0,
    createdAt DATETIME, updatedAt DATETIME
);

CREATE TABLE IF NOT EXISTS Services (
    id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(255), description TEXT, category VARCHAR(255),
    masterId INT, createdAt DATETIME, updatedAt DATETIME
);

CREATE TABLE IF NOT EXISTS Bookings (
    id INT AUTO_INCREMENT PRIMARY KEY, bookingDate DATE, timeSlot ENUM('morning','afternoon','evening'),
    address VARCHAR(255), phone VARCHAR(255), problemDescription TEXT, isAutoGenerated TINYINT(1) DEFAULT 0,
    clientId INT, serviceId INT, status ENUM('pending','confirmed','in_progress','completed','cancelled'),
    price FLOAT, masterNotes TEXT, createdAt DATETIME, updatedAt DATETIME
);

CREATE TABLE IF NOT EXISTS Reviews (
    id INT AUTO_INCREMENT PRIMARY KEY, rating INT, comment TEXT, createdAt DATETIME, updatedAt DATETIME,
    clientId INT, masterId INT, bookingId INT
);

CREATE TABLE IF NOT EXISTS Sensors (
    id INT AUTO_INCREMENT PRIMARY KEY, chipId VARCHAR(255), name VARCHAR(255), type ENUM('water_leak','smoke','temp'),
    status VARCHAR(255), lastValue FLOAT, userId INT, createdAt DATETIME, updatedAt DATETIME
);


