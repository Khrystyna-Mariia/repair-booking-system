const express = require('express');
const router = express.Router();

module.exports = (Sensor, Booking, User) => {
  router.post('/update', async (req, res) => {
    try {
      const { chipId, userId, currentTemp, sensorData, isAlert } = req.body;

      let [sensor, created] = await Sensor.findOrCreate({
        where: { chipId: chipId },
        defaults: { userId: userId, name: `Датчик ${chipId.substring(0, 4)}`, type: 'temp' }
      });

      await sensor.update({ lastValue: currentTemp });

      if (isAlert) {
        // Знаходимо користувача, щоб взяти його контакти
        const owner = await User.findByPk(userId);
        
        const existingBooking = await Booking.findOne({
          where: { clientId: userId, isAutoGenerated: true, status: 'pending' }
        });

        if (!existingBooking) {
          await Booking.create({
            bookingDate: new Date(),
            timeSlot: 'morning',
            address: owner?.address || 'Адреса не вказана', 
            phone: owner?.phone || 'Не вказано',
            problemDescription: `🚨 IoT ALERT: ${sensor.name} (ID: ${chipId}) - ${sensorData}`,
            status: 'pending',
            isAutoGenerated: true,
            clientId: userId
          });
        }
      }
      res.status(200).json({ message: "OK", sensor });
    } catch (error) {
      res.status(500).json({ error: error.message });
    }
  });

  // ОНОВЛЕННЯ НАЗВИ ДАТЧИКА
  router.put('/:id', async (req, res) => {
    try {
      const { name } = req.body;
      await Sensor.update({ name }, { where: { id: req.params.id } });
      res.json({ message: "Назву оновлено" });
    } catch (error) {
      res.status(500).json({ error: error.message });
    }
  });
  // GET: Отримати датчики
  router.get('/', async (req, res) => {
    try {
      const { userId } = req.query;
      console.log("Запит датчиків для користувача ID:", userId); 
      
      const sensors = await Sensor.findAll({ where: { userId: userId } });
      res.json(sensors);
    } catch (error) {
      console.error("Помилка на сервері (GET SENSORS):", error);
      res.status(500).json({ error: error.message });
    }
  });

  // POST: Додати датчик
  router.post('/', async (req, res) => {
    try {
      const { name, type, userId } = req.body;
      console.log("Спроба реєстрації датчика:", { name, type, userId });
      
      const sensor = await Sensor.create({ name, type, userId });
      res.status(201).json(sensor);
    } catch (error) {
      console.error("Помилка на сервері (POST SENSOR):", error);
      res.status(500).json({ error: error.message });
    }
  });

  // POST: Аварія (Alert)
  router.post('/alert', async (req, res) => {
    try {
      const { sensorId, sensorData } = req.body;
      console.log(` СИГНАЛ ВІД ДАТЧИКА ID: ${sensorId}. Дані: ${sensorData}`);

      const sensor = await Sensor.findByPk(sensorId, { include: [User] });
      if (!sensor) return res.status(404).json({ error: "Датчик не знайдено" });

      const existingBooking = await Booking.findOne({
        where: {
          clientId: sensor.userId,
          isAutoGenerated: true,
          status: 'pending', // Тільки якщо вона ще "Очікує"
        }
      });

      if (existingBooking) {
        console.log(` Заявка для датчика ${sensor.name} вже існує (ID: ${existingBooking.id}). Пропускаємо.`);
        return res.status(200).json({ 
          message: "Заявка вже була створена раніше і знаходиться в черзі",
          booking: existingBooking 
        });
      }
      const autoBooking = await Booking.create({
        bookingDate: new Date(),
        timeSlot: 'morning',
        address: sensor.User?.address || 'Адреса IoT пристрою',
        phone: sensor.User?.phone || '000',
        problemDescription: `🚨 IoT ALERT: ${sensor.name} - ${sensorData}`,
        status: 'pending',
        isAutoGenerated: true,
        clientId: sensor.userId,
        serviceId: null 
      });

      res.status(201).json({ message: "Створено нову заявку", booking: autoBooking });
    } catch (error) {
      console.error("ALERT ERROR:", error);
      res.status(500).json({ error: error.message });
    }
  });

  // DELETE: Видалити датчик
  router.delete('/:id', async (req, res) => {
    try {
      const { id } = req.params;
      const deleted = await Sensor.destroy({ where: { id: id } });
      if (deleted) {
        res.json({ message: "Датчик видалено успішно" });
      } else {
        res.status(404).json({ message: "Датчик не знайдено" });
      }
    } catch (error) {
      console.error("Помилка видалення датчика:", error);
      res.status(500).json({ error: error.message });
    }
  });
  
  return router;
};