const { DataTypes } = require('sequelize');

module.exports = (sequelize) => {
  const Booking = sequelize.define('Booking', {
    id: {
      type: DataTypes.INTEGER,
      autoIncrement: true,
      primaryKey: true,
    },
    bookingDate: {
      type: DataTypes.DATEONLY, 
      allowNull: false,
    },
    timeSlot: {
      type: DataTypes.ENUM('morning', 'afternoon', 'evening'), 
      allowNull: false,
    },
    address: {
      type: DataTypes.STRING,
      allowNull: false,
    },
    phone: {
      type: DataTypes.STRING,
      allowNull: false,
    },
    problemDescription: {
      type: DataTypes.TEXT,
      allowNull: false, 
    },
    
    isAutoGenerated: {
      type: DataTypes.BOOLEAN, // Прапорець, чи була заявка створена датчиком автоматично
      defaultValue: false,
    },
    
    clientId: {
      type: DataTypes.INTEGER,
      allowNull: true 
    },
    serviceId: {
      type: DataTypes.INTEGER,
      allowNull: true
    },
    status: {
  type: DataTypes.ENUM('pending', 'confirmed', 'in_progress', 'completed', 'cancelled'),
  defaultValue: 'pending'
},
price: {
  type: DataTypes.FLOAT,
  allowNull: true
},
masterNotes: {
  type: DataTypes.TEXT,
  allowNull: true
}
    
  });

  return Booking;
};